-- AR Study Hub schema for Supabase
-- Run in Supabase Dashboard -> SQL Editor.
-- This script creates role profiles, materials metadata, and a private file bucket.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  subject text not null check (char_length(subject) between 1 and 80),
  semester text,
  storage_path text not null unique,
  file_name text not null,
  uploaded_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.materials enable row level security;

-- Create a profile automatically for new auth users. New accounts are students.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)), 'student')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Helper: checks role from the server-side profiles table.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- A signed-in user can read their own profile; admins can read profiles.
create policy "profiles read own or admin" on public.profiles
for select to authenticated
using (id = (select auth.uid()) or public.is_admin());

-- Only admins may change roles/profile data. Do not allow users to promote themselves.
create policy "profiles update admin only" on public.profiles
for update to authenticated
using (public.is_admin())
with check (public.is_admin());

create policy "materials read authenticated" on public.materials
for select to authenticated
using (true);

create policy "materials insert admin only" on public.materials
for insert to authenticated
with check (public.is_admin() and uploaded_by = (select auth.uid()));

create policy "materials update admin only" on public.materials
for update to authenticated
using (public.is_admin())
with check (public.is_admin());

create policy "materials delete admin only" on public.materials
for delete to authenticated
using (public.is_admin());

-- Private storage bucket; students may read files through authenticated policies.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'study-materials',
  'study-materials',
  false,
  20971520,
  array[
    'application/pdf',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.ms-powerpoint',
    'application/vnd.openxmlformats-officedocument.presentationml.presentation'
  ]
)
on conflict (id) do update set public = false, file_size_limit = 20971520;

create policy "study files readable by authenticated users"
on storage.objects for select to authenticated
using (bucket_id = 'study-materials');

create policy "admins upload study files"
on storage.objects for insert to authenticated
with check (bucket_id = 'study-materials' and public.is_admin());

create policy "admins update study files"
on storage.objects for update to authenticated
using (bucket_id = 'study-materials' and public.is_admin())
with check (bucket_id = 'study-materials' and public.is_admin());

create policy "admins delete study files"
on storage.objects for delete to authenticated
using (bucket_id = 'study-materials' and public.is_admin());

